package telemetry

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
)

// The local segment classifier (telemetry plan Step 5.6). It reads a prompt's
// text ON THIS MACHINE and returns only a closed-vocabulary tag; the text never
// leaves the derive pass and no field carries it.
//
// "system_nudge" (plan §5.1): anything the app or agent harness injected as a
// turn that the user did not type: task and agent notifications, system
// reminders, hook feedback, session-continuation summaries and similar
// auto-composed guidance. Everything else that arrives as a prompt is
// "user_prompt". Model calls driven by tool results are "tool_call" (a separate
// segment of the cycle, see derive_cycles.go). Classification is heuristic and
// improves over time through the local rules file (nudge-scan).

// Segment tags (contract vocabulary Segment).
const (
	SegmentUserPrompt  = "user_prompt"
	SegmentSystemNudge = "system_nudge"
	SegmentToolCall    = "tool_call"
)

// NudgeRules is the classifier's signature: built-in defaults (the bootstrap
// from the 2026-10-18 pareto over a real store) plus any local additions.
type NudgeRules struct {
	// MarkupTags: a prompt whose first token is <tag ...> is a nudge.
	MarkupTags []string `json:"markup_tags"`
	// Prefixes: a prompt starting with one of these harness phrases is a nudge.
	Prefixes []string `json:"prefixes"`
	// TextHashes: sha256 (hex) of whole prompts known to be harness templates
	// (repeated verbatim). Hashes only, so the rules file holds no text.
	TextHashes []string `json:"text_hashes"`
}

// DefaultNudgeRules is the bootstrap signature. Pareto over a real store
// (2026-10-18, counts only): <task-notification> 23, <system-reminder> 9,
// <agent-message> 3, "Another Claude session sent a message" 3, "Stop hook
// feedback" 1, "This session is being continued" 1 (all Claude Code). Plain
// short commands such as "continue" stay user prompts: a person types them as
// often as a loop sends them, and the transcript cannot tell which.
func DefaultNudgeRules() NudgeRules {
	return NudgeRules{
		MarkupTags: []string{
			"task-notification", "system-reminder", "agent-message",
			"user-prompt-submit-hook", "local-command-stdout", "local-command-stderr",
			"local-command-caveat", "bash-stdout", "bash-stderr",
		},
		Prefixes: []string{
			"Another Claude session sent a message",
			"Stop hook feedback",
			"This session is being continued from a previous conversation",
			"[SYSTEM NOTIFICATION",
			"Caveat: The messages below were generated by the user while running local commands",
			"Your task is to create a detailed summary of the conversation",
		},
	}
}

var leadingTagRe = regexp.MustCompile(`^<([A-Za-z][\w:-]{0,40})`)

// LeadingTag returns the markup tag a prompt opens with ("" when none).
func LeadingTag(text string) string {
	m := leadingTagRe.FindStringSubmatch(strings.TrimLeft(text, " \t\r\n"))
	if m == nil {
		return ""
	}
	return strings.ToLower(m[1])
}

// TextHash is the signature hash of a whole prompt (trimmed).
func TextHash(text string) string {
	sum := sha256.Sum256([]byte(strings.TrimSpace(text)))
	return hex.EncodeToString(sum[:])
}

// Classify returns the segment tag for a prompt's text.
func (r NudgeRules) Classify(text string) string {
	s := strings.TrimLeft(text, " \t\r\n")
	if tag := LeadingTag(s); tag != "" {
		for _, t := range r.MarkupTags {
			if tag == t {
				return SegmentSystemNudge
			}
		}
	}
	for _, p := range r.Prefixes {
		if p != "" && strings.HasPrefix(s, p) {
			return SegmentSystemNudge
		}
	}
	if len(r.TextHashes) > 0 {
		h := TextHash(s)
		for _, x := range r.TextHashes {
			if x == h {
				return SegmentSystemNudge
			}
		}
	}
	return SegmentUserPrompt
}

// Merge returns r plus any entries of more that r lacks (sorted, deduped).
func (r NudgeRules) Merge(more NudgeRules) NudgeRules {
	return NudgeRules{
		MarkupTags: union(r.MarkupTags, more.MarkupTags),
		Prefixes:   union(r.Prefixes, more.Prefixes),
		TextHashes: union(r.TextHashes, more.TextHashes),
	}
}

func union(a, b []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range append(append([]string{}, a...), b...) {
		if s != "" && !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	sort.Strings(out)
	return out
}

// LoadNudgeRules returns the defaults merged with the local rules file at path
// (a missing file is not an error). The file is written by
// `observer telemetry nudge-scan --apply` and holds tag names, harness phrases
// and hashes only.
func LoadNudgeRules(path string) (NudgeRules, error) {
	rules := DefaultNudgeRules()
	if path == "" {
		return rules, nil
	}
	raw, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return rules, nil
	}
	if err != nil {
		return rules, fmt.Errorf("telemetry: read nudge rules: %w", err)
	}
	var local NudgeRules
	if err := json.Unmarshal(raw, &local); err != nil {
		return rules, fmt.Errorf("telemetry: parse nudge rules %s: %w", path, err)
	}
	return rules.Merge(local), nil
}

// SaveNudgeRules writes the local additions (0600).
func SaveNudgeRules(path string, r NudgeRules) error {
	raw, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(raw, '\n'), 0o600)
}
