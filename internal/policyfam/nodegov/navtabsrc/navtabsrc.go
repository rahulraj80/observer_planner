package navtabsrc

import (
	"bytes"
	"fmt"
	"go/format"
	"regexp"
	"strconv"
	"strings"
)

// Tab is one tab of a page: its `?tab=` id and its visible label.
type Tab struct {
	ID    string
	Label string
}

// Page is one tabbed node-dashboard page: its nav id (web/src/lib/nav.ts) and
// its tabs in strip order.
type Page struct {
	NavID string
	Tabs  []Tab
}

// routeRe matches one NODE_TAB_ROUTES row:
// { navId: "security", path: "/security", tabs: SECURITY_TABS },
var routeRe = regexp.MustCompile(`\{\s*navId:\s*"([a-z0-9-]+)",\s*path:\s*"[^"]*",\s*tabs:\s*([A-Z0-9_]+)\s*\}`)

// tableRe matches one `export const X_TABS = pageTabs([...] as const, {...})`
// declaration and captures the constant name, the id array body and the label
// object body.
var tableRe = regexp.MustCompile(`(?s)export\s+const\s+([A-Z0-9_]+)\s*=\s*pageTabs\(\s*\[([^\]]*)\]\s*as\s+const\s*,\s*\{([^}]*)\}`)

// quotedRe matches one double-quoted string literal.
var quotedRe = regexp.MustCompile(`"([^"\\]*)"`)

// labelRe matches one `key: "Label"` pair, the key either quoted or bare.
var labelRe = regexp.MustCompile(`(?:"([a-z0-9-]+)"|([a-z0-9_]+))\s*:\s*"([^"\\]*)"`)

// idRe is the shape every page and tab id must have.
var idRe = regexp.MustCompile(`^[a-z0-9-]+$`)

// Parse reads the two SPA sources and returns every tabbed page in
// NODE_TAB_ROUTES order. It fails rather than guess: a route naming a table
// the tabs file does not declare, a tab without a label, a label for no tab,
// a duplicate id or an id outside [a-z0-9-] are all errors, because a silently
// partial vocabulary is a publish lint that disagrees with the page.
func Parse(routesTS, tabsTS []byte) ([]Page, error) {
	tables := map[string][]Tab{}
	for _, m := range tableRe.FindAllSubmatch(tabsTS, -1) {
		name := string(m[1])
		var ids []string
		for _, q := range quotedRe.FindAllSubmatch(m[2], -1) {
			ids = append(ids, string(q[1]))
		}
		labels := map[string]string{}
		for _, l := range labelRe.FindAllSubmatch(m[3], -1) {
			key := string(l[1])
			if key == "" {
				key = string(l[2])
			}
			labels[key] = string(l[3])
		}
		if len(ids) == 0 {
			return nil, fmt.Errorf("navtabsrc: %s declares no tab ids", name)
		}
		seen := map[string]bool{}
		tabs := make([]Tab, 0, len(ids))
		for _, id := range ids {
			if !idRe.MatchString(id) {
				return nil, fmt.Errorf("navtabsrc: %s tab id %q is not [a-z0-9-]+", name, id)
			}
			if seen[id] {
				return nil, fmt.Errorf("navtabsrc: %s names tab %q twice", name, id)
			}
			seen[id] = true
			label, ok := labels[id]
			if !ok || strings.TrimSpace(label) == "" {
				return nil, fmt.Errorf("navtabsrc: %s tab %q has no label", name, id)
			}
			tabs = append(tabs, Tab{ID: id, Label: label})
		}
		for key := range labels {
			if !seen[key] {
				return nil, fmt.Errorf("navtabsrc: %s labels %q, which is not one of its tab ids", name, key)
			}
		}
		tables[name] = tabs
	}
	var pages []Page
	seenPage := map[string]bool{}
	for _, m := range routeRe.FindAllSubmatch(routesTS, -1) {
		nav, table := string(m[1]), string(m[2])
		tabs, ok := tables[table]
		if !ok {
			return nil, fmt.Errorf("navtabsrc: route %q names %s, which the tabs file does not declare", nav, table)
		}
		if seenPage[nav] {
			return nil, fmt.Errorf("navtabsrc: route %q is listed twice", nav)
		}
		seenPage[nav] = true
		pages = append(pages, Page{NavID: nav, Tabs: tabs})
	}
	if len(pages) == 0 {
		return nil, fmt.Errorf("navtabsrc: parsed no NODE_TAB_ROUTES rows; the file's shape changed and this parser needs updating")
	}
	return pages, nil
}

// Render returns the gofmt'd Go source of nodegov's navtabs_gen.go.
func Render(pages []Page) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/policyfam/nodegov/navtabsrc/gen from\n")
	b.WriteString("// web/src/lib/pageTabRoutes.ts and web/src/lib/nodePageTabs.ts. DO NOT EDIT.\n\n")
	b.WriteString("package nodegov\n\n")
	b.WriteString("// NavTabs is every tabbed node-dashboard page with its tabs in strip order,\n")
	b.WriteString("// generated from the SPA's own tab tables (run `go generate\n")
	b.WriteString("// ./internal/policyfam/nodegov` after changing them).\n")
	b.WriteString("var NavTabs = []NavTabPage{\n")
	for _, p := range pages {
		fmt.Fprintf(&b, "\t{Page: %s, Tabs: []NavTab{\n", strconv.Quote(p.NavID))
		for _, t := range p.Tabs {
			fmt.Fprintf(&b, "\t\t{ID: %s, Label: %s},\n", strconv.Quote(t.ID), strconv.Quote(t.Label))
		}
		b.WriteString("\t}},\n")
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("navtabsrc.Render: %w", err)
	}
	return out, nil
}
