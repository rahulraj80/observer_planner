func dir(setting, mode, value string) orgcontract.AgentConfigDirective {
	return orgcontract.AgentConfigDirective{Setting: setting, Mode: mode, Value: json.RawMessage(value), Layer: "org", Policy: "Baseline"}
}

const (
	enf = orgcontract.AgentConfigModeEnforced
	def = orgcontract.AgentConfigModeDefault
)

func render(t *testing.T, ds ...orgcontract.AgentConfigDirective) Bundle {
	t.Helper()
	b, err := FromPolicy(PolicyInput{
		Body:     orgcontract.AgentConfigPolicyBody{Directives: ds, Policies: []string{"Baseline"}},
		Audience: "the whole organization", Version: 7,
	})
	if err != nil {
		t.Fatalf("FromPolicy: %v", err)
	}
	return b
}

func toolOf(b Bundle, name string) (ToolBundle, bool) {
	for _, t := range b.Tools {
		if t.Tool == name {
			return t, true
		}
	}
	return ToolBundle{}, false
}

func artifact(t ToolBundle, name string) (Artifact, bool) {
	for _, a := range t.Artifacts {
		if a.Name == name {
			return a, true
		}
	}
	return Artifact{}, false
}

func skipReason(b Bundle, setting string) string {
	for _, s := range b.Unplaced {
		if s.Setting == setting {
			return s.Reason
		}
	}
	return ""
}

// TestFromPolicyPlacement is the placement table: one row per case, each
// naming where (or why not) one directive lands.
func TestFromPolicyPlacement(t *testing.T) {
	cases := []struct {
		name     string
		d        orgcontract.AgentConfigDirective
		tool     string // bundle tool the value lands under ("" = skipped)
		artifact string
		contains []string
		strength Strength
		skip     string
	}{
		{
			name: "claude code enforced model goes to managed-settings.json", d: dir("claude-code/model", enf, `"sonnet"`),
			tool: "claude-code", artifact: "claude-code/managed-settings.json", contains: []string{`"model": "sonnet"`}, strength: StrengthTamperProof,
		},
		{
			name: "claude code default has no default layer", d: dir("claude-code/model", def, `"sonnet"`), skip: ReasonNoDefaultLayer,
		},
		{
			name: "codex enforced model is a launch default in managed_config.toml", d: dir("codex/model", enf, `"gpt-5-codex"`),
			tool: "codex", artifact: "codex/managed_config.toml", contains: []string{`model = "gpt-5-codex"`, "# Generated by Observer"}, strength: StrengthLaunchReset,
		},
		{
			name: "codex default model goes to the system config.toml", d: dir("codex/model", def, `"gpt-5-codex"`),
			tool: "codex", artifact: "codex/config.toml", contains: []string{`model = "gpt-5-codex"`}, strength: StrengthDefaultOnly,
		},
		{
			name: "codex enforced approval policy becomes a requirements constraint", d: dir("codex/approval_policy", enf, `"on-request"`),
			tool: "codex", artifact: "codex/requirements.toml", contains: []string{`allowed_approval_policies = ["on-request"]`}, strength: StrengthTamperProof,
		},
		{
			name: "codex enforced disabled web search is the empty allow list", d: dir("codex/web_search", enf, `"disabled"`),
			tool: "codex", artifact: "codex/requirements.toml", contains: []string{"allowed_web_search_modes = []"}, strength: StrengthTamperProof,
		},
		{
			name: "gemini system settings are bypassable", d: dir("gemini-cli/model.name", enf, `"gemini-2.5-pro"`),
			tool: "gemini-cli", artifact: "gemini-cli/settings.json", contains: []string{`"name": "gemini-2.5-pro"`}, strength: StrengthBypassable,
		},
		{
			name: "gemini default goes to system-defaults.json", d: dir("gemini-cli/model.name", def, `"gemini-2.5-pro"`),
			tool: "gemini-cli", artifact: "gemini-cli/system-defaults.json", strength: StrengthDefaultOnly,
		},
		{
			name: "opencode is tamper-proof through the macOS profile", d: dir("opencode/model", enf, `"anthropic/claude-sonnet-4-5"`),
			tool: "opencode", artifact: "opencode/opencode.mobileconfig", contains: []string{"<key>model</key>", "ai.opencode.managed"}, strength: StrengthTamperProof,
		},
		{
			name: "kilo code lands in the shared kilo managed directory", d: dir("kilo-code/model", enf, `"anthropic/claude-sonnet-4-5"`),
			tool: "kilo-code-cli", artifact: "kilo-code-cli/kilo.jsonc", contains: []string{`"model"`},
		},
		{
			name: "grok enforced sandbox profile is pinned in requirements.toml", d: dir("grok/sandbox.profile", enf, `"workspace"`),
			tool: "grok", artifact: "grok/requirements.toml", contains: []string{"[sandbox]", `profile = "workspace"`}, strength: StrengthTamperProof,
		},
		{
			name: "a kiro allow rule is refused (the managed file fails closed)", d: dir("kiro-cli/rules", enf, `[{"capability":"shell","match":["*"],"effect":"allow"}]`),
			skip: ReasonValueRefused,
		},
		{
			name: "a kiro deny rule is restrict-only", d: dir("kiro-cli/rules", enf, `[{"capability":"shell","match":["rm -rf *"],"effect":"deny"}]`),
			tool: "kiro-cli", artifact: "kiro-cli/managed-settings.json", contains: []string{`"effect": "deny"`}, strength: StrengthRestrictOnly,
		},
		{
			name: "a per-project value stays with lever B", d: func() orgcontract.AgentConfigDirective {
				d := dir("claude-code/model", enf, `"sonnet"`)
				d.Project = strings.Repeat("a", 64)
				return d
			}(), skip: ReasonProjectScope,
		},
		{
			name: "an unknown setting is reported", d: dir("nope/thing", enf, `true`), skip: ReasonUnknownSetting,
		},
		{
			name: "a tool with no managed layer is reported", d: dir("aider/model", enf, `"gpt-4o"`), skip: ReasonNoManagedLayer,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if _, ok := agentconfig.Setting(tc.d.Setting); !ok && tc.skip != ReasonUnknownSetting {
				t.Fatalf("test setting %s is not in the catalogue", tc.d.Setting)
			}
			b := render(t, tc.d)
			if tc.skip != "" {
				if got := skipReason(b, tc.d.Setting); got != tc.skip {
					t.Fatalf("skip reason = %q, want %q (unplaced %+v)", got, tc.skip, b.Unplaced)
				}
				return
			}
			tb, ok := toolOf(b, tc.tool)
			if !ok {
				t.Fatalf("no bundle for %s; unplaced %+v", tc.tool, b.Unplaced)
			}
			a, ok := artifact(tb, tc.artifact)
			if !ok {
				names := []string{}
				for _, x := range tb.Artifacts {
					names = append(names, x.Name)
				}
				t.Fatalf("no artifact %s in %v", tc.artifact, names)
			}
			for _, want := range tc.contains {
				if !strings.Contains(a.Content, want) {
					t.Errorf("%s lacks %q:\n%s", a.Name, want, a.Content)
				}
			}
			if tc.strength != "" && tb.Strength != tc.strength {
				t.Errorf("tool strength = %s, want %s", tb.Strength, tc.strength)
			}
		})
	}
}

// TestClaudeCodeChannels pins the three channels of one Claude Code value:
// the file, the native-key profile and the HKLM Settings JSON value.
func TestClaudeCodeChannels(t *testing.T) {
	b := render(t, dir("claude-code/model", enf, `"sonnet"`), dir("claude-code/permissions.defaultMode", enf, `"default"`))
	tb, _ := toolOf(b, "claude-code")
	prof, ok := artifact(tb, "claude-code/managed-settings.mobileconfig")
	if !ok || !strings.Contains(prof.Content, "<string>com.anthropic.claudecode</string>") || !strings.Contains(prof.Content, "<key>permissions</key>") {
		t.Fatalf("profile: %s", prof.Content)
	}
	reg, ok := artifact(tb, "claude-code/managed-settings.reg")
	if !ok || !strings.Contains(reg.Content, `[HKEY_LOCAL_MACHINE\SOFTWARE\Policies\ClaudeCode]`) || !strings.Contains(reg.Content, `"Settings"="{\"model\":\"sonnet\"`) {
		t.Fatalf("reg: %s", reg.Content)
	}
	if reg.Encoding != EncodingUTF16LE || !bytes.HasPrefix(reg.Bytes(), []byte{0xFF, 0xFE}) {
		t.Fatal("a .reg file must be UTF-16LE with a BOM")
	}
	if !strings.Contains(reg.Content, "\r\n") {
		t.Fatal("a .reg file uses CRLF")
	}
}

// TestCodexProfilesCarryBase64 pins the Codex MDM convention: the profile
// key holds the base64 of the rendered TOML.
func TestCodexProfilesCarryBase64(t *testing.T) {
	b := render(t, dir("codex/sandbox_mode", enf, `"workspace-write"`))
	tb, _ := toolOf(b, "codex")
	file, _ := artifact(tb, "codex/requirements.toml")
	prof, ok := artifact(tb, "codex/requirements.mobileconfig")
	if !ok {
		t.Fatal("no requirements profile")
	}
	want := base64.StdEncoding.EncodeToString([]byte(file.Content))
	if !strings.Contains(prof.Content, "<key>requirements_toml_base64</key>") || !strings.Contains(prof.Content, want) {
		t.Fatalf("profile does not carry the file's base64:\n%s", prof.Content)
	}
}

func TestDeterministicAndZip(t *testing.T) {
	ds := []orgcontract.AgentConfigDirective{
		dir("claude-code/model", enf, `"sonnet"`), dir("codex/approval_policy", enf, `"never"`), dir("codex/model", def, `"o3"`),
	}
	a, b := render(t, ds...), render(t, ds...)
	za, err := a.Zip()
	if err != nil {
		t.Fatal(err)
	}
	zb, _ := b.Zip()
	if !bytes.Equal(za, zb) {
		t.Fatal("the same policy must render the same archive")
	}
	zr, err := zip.NewReader(bytes.NewReader(za), int64(len(za)))
	if err != nil {
		t.Fatal(err)
	}
	names := map[string]bool{}
	for _, f := range zr.File {
		names[f.Name] = true
	}
	for _, want := range []string{"README.md", "claude-code/README.md", "claude-code/managed-settings.json", "codex/requirements.toml", "codex/config.toml"} {
		if !names[want] {
			t.Errorf("zip lacks %s (has %v)", want, names)
		}
	}
	if !strings.Contains(a.Readme, "| claude-code | tamper-proof | tamper-proof | tamper-proof |") {
		t.Errorf("README lock table:\n%s", a.Readme)
	}
}

// TestLayerTable pins the table's invariants: every row names a real
// administrator file of the catalogue; a policy DEFAULT never lands in an
// override layer (it would become a lock) and an enforced value never in a
// default layer; every row is grounded; derived rules point at real rows.
func TestLayerTable(t *testing.T) {
	for _, l := range Layers() {
		f, ok := fileRow(l.FileID)
		if !ok {
			t.Errorf("%s: no catalogue file row", l.FileID)
			continue
		}
		if f.WriteNeeds != agentconfig.PrivAdminRoot {
			t.Errorf("%s: a managed layer must be an administrator file, got %s", l.FileID, f.WriteNeeds)
		}
		for _, m := range l.Modes {
			switch {
			case m == def && f.Scope != agentconfig.ScopeSystem:
				t.Errorf("%s: a default lands only in a system (lowest admin) layer, not %s", l.FileID, f.Scope)
			case m == enf && f.Scope != agentconfig.ScopeManaged:
				t.Errorf("%s: an enforced value lands only in a managed (override) layer, not %s", l.FileID, f.Scope)
			}
		}
		if len(l.Sources) == 0 || strings.TrimSpace(l.Note) == "" {
			t.Errorf("%s: every row names its sources and a note", l.FileID)
		}
		if strings.ContainsAny(l.Note, "\u2013\u2014") {
			t.Errorf("%s: no en or em dashes in copy", l.FileID)
		}
		if _, ok := strengthRank[l.Strength]; !ok {
			t.Errorf("%s: unknown strength %q", l.FileID, l.Strength)
		}
	}
	for _, d := range derivedRules() {
		if _, ok := agentconfig.Setting(d.From); !ok {
			t.Errorf("derived %s: %s is not in the catalogue", d.Name, d.From)
		}
		if _, ok := layerByFile(d.To); !ok {
			t.Errorf("derived %s: %s is not a layer", d.Name, d.To)
		}
	}
}

// TestLocksAreHonest pins the per-tool lock table: every catalogued tool is
// listed; a tool with nothing lever A can lock is tamper-evident with a
// reason; a weak OS is never reported stronger than tamper-evident.
func TestLocksAreHonest(t *testing.T) {
	locks := Locks()
	byTool := map[string]ToolLock{}
	for _, l := range locks {
		byTool[l.Tool] = l
		if l.Best == StrengthTamperEvident && strings.TrimSpace(l.Note) == "" {
			t.Errorf("%s: a tamper-evident tool needs its reason", l.Tool)
		}
	}
	want := map[string]map[string]Strength{
		"claude-code": {"linux": StrengthTamperProof, "darwin": StrengthTamperProof, "windows": StrengthTamperProof},
		"codex":       {"linux": StrengthTamperProof, "darwin": StrengthTamperProof, "windows": StrengthTamperProof},
		"gemini-cli":  {"linux": StrengthBypassable, "darwin": StrengthBypassable, "windows": StrengthBypassable},
		"opencode":    {"linux": StrengthBypassable, "darwin": StrengthTamperProof, "windows": StrengthBypassable},
		"aider":       {"linux": StrengthTamperEvident, "darwin": StrengthTamperEvident, "windows": StrengthTamperEvident},
	}
	for tool, perOS := range want {
		l, ok := byTool[tool]
		if !ok {
			t.Errorf("%s missing from the lock table", tool)
			continue
		}
		for os, s := range perOS {
			if l.PerOS[os] != s {
				t.Errorf("%s on %s = %s, want %s", tool, os, l.PerOS[os], s)
			}
		}
	}
	for _, c := range agentconfig.Coverage() {
		if c.Status == agentconfig.CoverageNoSurface {
			continue
		}
		if _, ok := byTool[c.Tool]; !ok {
			t.Errorf("%s is catalogued but not in the lock table", c.Tool)
		}
	}
}
