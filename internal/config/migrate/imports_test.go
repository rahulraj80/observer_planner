package migrate

import (
	"testing"

	"github.com/marmutapp/superbased-observer/internal/testsupport/importpin"
)

// TestNoForbiddenImports pins the pure-logic boundary: the read/write boundary
// lives in internal/config (MigrateFile) and the call sites.
func TestNoForbiddenImports(t *testing.T) {
	importpin.Check(t, importpin.Spec{
		Forbidden: []string{
			"database/sql",
			"net/http",
			"github.com/fsnotify/fsnotify",
			"os",
		},
		Reason: "keep migrate pure",
	})
}
