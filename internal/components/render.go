package components

import (
	"fmt"
	"sort"
	"strings"
)

// DocsPath is where the generated reference lives, relative to the repo
// root.
const DocsPath = "docs/components.md"

// RenderMarkdown renders docs/components.md from the catalog. It is
// deterministic (same catalog, same bytes) so a drift gate can compare it
// with the committed file.
func RenderMarkdown() string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("<!-- Code generated by cmd/sbo-components gen-docs from internal/components. DO NOT EDIT. -->\n\n")
	w("# Components\n\n")
	w("The component catalog (catalog version %d): every named, catalogued slice of SuperBased Observer, ", CatalogVersion)
	w("what it adds to a machine, and where the modular packaging plan takes it ")
	w("(`docs/plans/modular-packaging-plan-2026-10-07.md`). Generated from `internal/components`; ")
	w("edit the catalog and run `go run ./cmd/sbo-components gen-docs`, never this file.\n\n")
	w("On a running node, `observer components list` and `observer components show <id>` print the same data, ")
	w("and the dashboard serves it at `GET /api/components`.\n\n")
	w("## Removal levels\n\n")
	w("| Level | Meaning |\n|---|---|\n")
	w("| L0 | Core. Always present. |\n")
	w("| L1 | Compiled out: its packages and the modules it alone brings are absent from the binary, proved by `go list -deps` with the distro's tags. |\n")
	w("| L2 | Installed but inert: compiled in, but no goroutine, listener, egress, file or vendor-config write. Not a CVE mitigation. |\n")
	w("| L3 | Runtime toggle: today's config keys. |\n\n")
	w("**Implemented** is what this build's code delivers today. **Target** is where the plan takes the component, ")
	w("with the phase that delivers it. A distro build (`scripts/build-distro.sh`) compiles out the excluded components ")
	w("that claim L1 and keeps the others inert (L2). npm, PyPI and the VS Code extension ship the `full` distro; ")
	w("GitHub releases also carry the `minimal`, `developer` and `managed` distros (from v1.36.0, installed with ")
	w("`scripts/install.sh` or `install.ps1`).\n\n")

	w("## Node distros\n\n")
	w("| Distro | Compiled components | Active by default | Omit tags |\n|---|---|---|---|\n")
	for _, d := range Distros() {
		w("| `%s` | %d | %d | %d |\n", d, len(InDistro(d)), len(DefaultActive(d)), len(OmitTags(d)))
	}
	w("\nCell values: `on` compiled in and active by default, `off` compiled in and inactive until selected, ")
	w("`cond` compiled in and active on a stated condition (enrolment), `out` not in the distro (compiled out when the ")
	w("component claims L1, otherwise its code stays in the binary, inert and not selectable).\n\n")

	w("## Node components\n\n")
	w("| Component | Class | Implemented | Target | minimal | developer | managed | full |\n|---|---|---|---|---|---|---|---|\n")
	for _, c := range ForBinary(BinaryNode) {
		if c.Class == ClassAdapter {
			continue
		}
		w("| [`%s`](#%s) %s | %s | %s | %s | %s | %s | %s | %s |\n", c.ID, anchor(c.ID), c.Title, c.Class,
			levels(c.Levels.Implemented), target(c.Levels), c.Distros[DistroMinimal], c.Distros[DistroDeveloper],
			c.Distros[DistroManaged], c.Distros[DistroFull])
	}

	w("\n## Adapters\n\n")
	w("One row per integration-registry tool id. Integration facts (proxy, hooks, MCP, routes, token tier) live in ")
	w("`internal/integration` and `observer adapters`. Every adapter is compiled into every prebuilt distro ")
	w("(`off` in minimal and managed, `on` in developer and full) and reaches L1 only through custom builds (P5).\n\n")
	w("| Component | Title | Package | Stability | Relations |\n|---|---|---|---|---|\n")
	for _, c := range ForBinary(BinaryNode) {
		if c.Class != ClassAdapter {
			continue
		}
		pkg := strings.Join(c.Packages, ", ")
		if pkg == "" {
			pkg = "in " + strings.Join(c.HostedIn, ", ")
		}
		w("| `%s` | %s | `%s` | %s | %s |\n", c.ID, c.Title, pkg, c.Stability, relations(c))
	}

	w("\n## Org server components\n\n")
	w("Two coarse images in this plan: `observer-org:<v>` (full) and `observer-org:<v>-core` (org.core and org.oidc). ")
	w("Choosing modules individually on the server is L2 (config and role).\n\n")
	w("| Component | Binary | Implemented | Target | full image | core image |\n|---|---|---|---|---|---|\n")
	for _, c := range All() {
		if c.Binary == BinaryNode {
			continue
		}
		w("| [`%s`](#%s) %s | %s | %s | %s | %s | %s |\n", c.ID, anchor(c.ID), c.Title, c.Binary,
			levels(c.Levels.Implemented), target(c.Levels), c.Images[ImageFull], c.Images[ImageCore])
	}

	w("\n## External artifacts\n\n")
	w("Installed outside the Observer binary; Observer does not control their lifecycle, so they never appear in the distro columns.\n\n")
	w("| Artifact | Kind | Platforms | Requires | States |\n|---|---|---|---|---|\n")
	for _, a := range Artifacts() {
		w("| `%s` %s | %s | %s | %s | %s |\n", a.ID, a.Title, a.Kind, strings.Join(a.Platforms, ", "),
			strings.Join(a.Requires, ", "), strings.Join(a.States, ", "))
	}
	for _, a := range Artifacts() {
		w("\n### %s\n\n%s\n\n", a.ID, a.About)
		w("- Source: %s\n- Signer: %s\n- Protocol: %s\n- Owner: %s\n", a.Source, a.Signer, a.Protocol, a.Ownership)
		w("- Not installed means: %s\n- Removal and leftovers: %s\n- Version lockstep: %s\n", a.NotInstalled, a.Removal, a.Lockstep)
		if a.VersionFile != "" {
			w("- Version file: `%s`\n", a.VersionFile)
		}
	}
	w("\nObserver registers no URL or protocol handler (no `x-scheme-handler`, no Windows URL protocol key, no editor URI handler), so there is no protocol-handler artifact to remove. ")
	w("`observer components artifacts` shows each artifact's state on this machine; `observer doctor components` warns on a stale, incompatible or leftover one.\n")

	w("\n## Component details\n")
	for _, c := range All() {
		if c.Class == ClassAdapter {
			continue
		}
		w("\n### %s\n\n", c.ID)
		w("**%s.** %s\n\n", c.Title, c.About)
		w("- Class: %s; binary: %s; stability: %s\n", c.Class, c.Binary, c.Stability)
		w("- Levels: implemented %s; target %s\n", levels(c.Levels.Implemented), target(c.Levels))
		if tag := c.BuildTag(); tag != "" {
			w("- Build tag: `%s`\n", tag)
		}
		list(w, "Packages", c.Packages, true)
		list(w, "Code hosted in", c.HostedIn, true)
		list(w, "Direct modules", c.DirectModules, true)
		list(w, "Requires", c.Requires, true)
		list(w, "Requires compiled", c.RequiresCompiled, true)
		list(w, "Bundles", c.Bundles, true)
		list(w, "Recommends", c.Recommends, true)
		list(w, "Conflicts", c.Conflicts, true)
		for _, l := range c.Surface.Listeners {
			key := ""
			if l.ConfigKey != "" {
				key = fmt.Sprintf(", moved by `%s`", l.ConfigKey)
			}
			w("- Listener: %s `%s` (auth: %s; %s%s)\n", l.Proto, l.Addr, l.Auth, l.Trigger, key)
		}
		for _, e := range c.Surface.Egress {
			w("- Egress: `%s`: %s (%s; %s)\n", e.Host, e.Purpose, e.Gate, e.Trigger)
		}
		list(w, "Files written", c.Surface.FilesWritten, false)
		list(w, "Other tools' config it edits", c.Surface.VendorConfigs, false)
		list(w, "OS integration", c.Surface.OSIntegration, false)
		list(w, "Processes it runs", c.Surface.Processes, false)
		list(w, "Credential stores", c.Surface.Credentials, false)
		list(w, "Tables", c.Tables, true)
		for _, m := range c.Migrations {
			w("- Migration `%s`: %s. %s\n", m.File, m.Class, m.Note)
		}
		list(w, "Routes", c.Routes, true)
		list(w, "CLI verbs", c.Verbs, true)
		list(w, "Config sections", c.ConfigKeys, true)
		for _, t := range c.Teardown {
			w("- Teardown: %s (%s)\n", t.What, t.Owner)
		}
		list(w, "Security ledger", c.Ledger, false)
		if c.RestartClass != "" {
			w("- Restart class: %s\n", c.RestartClass)
		}
		if c.Note != "" {
			w("- Note: %s\n", c.Note)
		}
	}

	w("\n## Build tags per distro\n\n")
	w("Generated from the catalog (`go run ./cmd/sbo-components tags --distro <name>`, which `scripts/build-distro.sh` ")
	w("passes to `go build`): the distro's omit tags plus its stamp tag `sbo_distro_<name>`. An omit tag removes code only ")
	w("for a component whose Implemented column has L1; every other excluded component stays in the binary, inert and not ")
	w("selectable in that distro (L2), and the binary lists it under `distro_out`. The stamp makes a node with no ")
	w("`[components]` block start from its distro's default set. `sbo-components proof` checks each artifact against this ")
	w("table. Today's release artifacts are still the unstamped `full` build.\n")
	for _, d := range Distros() {
		tags := DistroTags(d)
		w("\n### %s\n\n", d)
		if len(tags) == 0 {
			w("No tags: the full product.\n")
			continue
		}
		w("```\n%s\n```\n", strings.Join(tags, ","))
	}
	return b.String()
}

func anchor(id string) string {
	return strings.NewReplacer(".", "", " ", "-").Replace(strings.ToLower(id))
}

func levels(ls []Level) string {
	if len(ls) == 0 {
		return "none"
	}
	s := make([]string, len(ls))
	for i, l := range ls {
		s[i] = string(l)
	}
	sort.Strings(s)
	return strings.Join(s, ", ")
}

func target(l Levels) string {
	s := levels(l.Target)
	if l.Phase != "" {
		s += " (" + l.Phase + ")"
	}
	return s
}

func relations(c Component) string {
	var parts []string
	if len(c.Bundles) > 0 {
		parts = append(parts, "bundles "+strings.Join(c.Bundles, ", "))
	}
	if len(c.Requires) > 0 {
		parts = append(parts, "requires "+strings.Join(c.Requires, ", "))
	}
	if len(c.Recommends) > 0 {
		parts = append(parts, "recommends "+strings.Join(c.Recommends, ", "))
	}
	if len(parts) == 0 {
		return "none"
	}
	return strings.Join(parts, "; ")
}

func list(w func(string, ...any), label string, xs []string, code bool) {
	if len(xs) == 0 {
		return
	}
	q := make([]string, len(xs))
	for i, x := range xs {
		if code {
			q[i] = "`" + x + "`"
		} else {
			q[i] = x
		}
	}
	w("- %s: %s\n", label, strings.Join(q, ", "))
}
