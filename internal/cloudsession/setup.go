// ClaudeSetupScriptLines are the lines a developer adds to a Claude Code
// cloud environment's setup script. That script is an environment setting,
// not a repository file, and it does not run in the repository: the vendor
// docs (https://code.claude.com/docs/en/cloud-environments, "Setup
// scripts") say it runs as root before Claude Code launches, name no working
// directory and no variable for the repository directory, and say the
// environment's variables are not set yet (CLAUDE_PROJECT_DIR is a hook
// variable). Live on 2026-11-03 a relative path failed ("cannot open ...:
// No such file") with the clone at /home/user/<repo>, a path no doc states.
// So the lines search the filesystem for the committed installer instead of
// assuming a path, skip the system trees, and run the first match (sorted)
// from its repository, which the post-install step's code index needs.
var ClaudeSetupScriptLines = claudeSetupScriptLines("/")

// claudeSetupScriptLines renders ClaudeSetupScriptLines searching below
// root (which ends in "/"; tests pass a temporary directory).
func claudeSetupScriptLines(root string) string {
	prune := []string{"proc", "sys", "dev", "run", "usr", "var"}
	var expr strings.Builder
	for i, p := range prune {
		if i > 0 {
			expr.WriteString(" -o ")
		}
		expr.WriteString("-path " + shellQuote(root+p))
	}
	expr.WriteString(" -o -name node_modules -o -name .git")
	suffix := "/" + SetupScriptPath
	return "# SuperBased Observer: this script does not run in the repository, so find the committed installer.\n" +
		"sbo_setup=$(find " + shellQuote(root) + " -maxdepth 8 \\( " + expr.String() + " \\) -prune -o -type f -path " + shellQuote("*"+suffix) + " -print 2>/dev/null | sort | head -n 1)\n" +
		"if [ -n \"$sbo_setup\" ]; then (cd \"${sbo_setup%" + suffix + "}\" && sh " + SetupScriptPath + "); else echo \"SuperBased Observer: no " + SetupScriptPath + " found in the cloned repository\" >&2; fi"
}
