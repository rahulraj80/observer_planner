// DefaultReleaseBaseURL is where release assets are fetched from, laid out
// like GitHub releases (<base>/download/<tag>/<asset>), the same default as
// scripts/install.sh.
const DefaultReleaseBaseURL = "https://github.com/superbasedapp/observer/releases"

// generatedPrefix starts the ownership line of every dedicated file this
// package generates. The line carries the sha256 of the file's body (every
// byte after the line), so remove deletes the file only when nobody edited
// it since; an edited file is left alone and reported.
const generatedPrefix = "# superbased-observer cloud-session: generated by `observer cloud-session init`, remove with `observer cloud-session remove`. sha256:"

// releaseTag is a release tag the setup script may pin.
var releaseTag = regexp.MustCompile(`^v[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?$`)

// withOwnership returns head + the ownership line + body, where head is
// the lines that must stay first (a shebang) and body is hashed.
func withOwnership(head, body string) string {
	sum := sha256.Sum256([]byte(body))
	return head + generatedPrefix + hex.EncodeToString(sum[:]) + "\n" + body
}

// ownedUnedited reports whether content is a generated file whose body still
// hashes to the value its ownership line records. generated=false when there
// is no ownership line at all (a file someone else wrote).
func ownedUnedited(content string) (generated, unedited bool) {
	i := strings.Index(content, generatedPrefix)
	if i < 0 {
		return false, false
	}
	rest := content[i+len(generatedPrefix):]
	nl := strings.IndexByte(rest, '\n')
	if nl < 0 {
		return true, false
	}
	want := rest[:nl]
	sum := sha256.Sum256([]byte(rest[nl+1:]))
	return true, want == hex.EncodeToString(sum[:])
}

// validateVendorKeys checks that every key is base64 of 32 bytes and not the
// all-zero placeholder (which verifies an all-zero signature trivially).
func validateVendorKeys(keys []string) error {
	if len(keys) == 0 {
		return fmt.Errorf("cloudsession: no vendor verification key; the setup script would install an unverified binary")
	}
	for _, k := range keys {
		raw, err := base64.StdEncoding.DecodeString(k)
		if err != nil || len(raw) != 32 {
			return fmt.Errorf("cloudsession: vendor key %q is not base64 of 32 bytes", k)
		}
		zero := true
		for _, b := range raw {
			if b != 0 {
				zero = false
				break
			}
		}
		if zero {
			return fmt.Errorf("cloudsession: refusing the all-zero placeholder vendor key")
		}
	}
	return nil
}

// renderSetupScript renders the POSIX sh installer. It installs exactly the
// pinned version, from the chosen source:
//
//   - npm (the default): the platform package tarball from the registry,
//     whose sha512 must equal the dist.integrity `init` pinned into the
//     script; a vendor signature shipped inside the package
//     (package/bin/observer.sig, raw Ed25519 over the binary) is verified
//     too when present.
//   - release: the release archive, whose sha256 must match the release's
//     SHA256SUMS and whose raw Ed25519 vendor signature (<archive>.sig, the
//     shape scripts/install.sh and internal/update verify) must verify
//     against a key compiled into Observer.
//
// A checksum or signature failure exits non-zero and installs nothing (fail
// closed); an unreachable host only warns. Either way the session goes on
// (a Claude Code cloud session ignores a failed setup script, CA-A2) and the
// committed hooks stay silent no-ops, because they test for the binary.
func renderSetupScript(opts PlanOptions) string {
	keys := strings.Join(opts.VendorKeys, " ")
	src := opts.installSource()
	var b strings.Builder
	b.WriteString(`# Installs a pinned, verified SuperBased Observer for Rail S
# (docs/cloud-sessions.md). Run it from the agent's setup step; it is
# idempotent, so a vendor snapshot that already holds the binary skips it.
set -eu

VERSION=` + shellQuote(opts.ObserverVersion) + `
SOURCE=` + string(src) + `
PREFIX=` + shellQuote(opts.installDir()) + `
`)
	switch src {
	case InstallRelease:
		b.WriteString(`BASE_URL=` + shellQuote(opts.releaseBaseURL()) + `
`)
	default:
		b.WriteString(`REGISTRY=` + shellQuote(opts.npmRegistry()) + `
# sha512 of each platform package tarball: the registry's dist.integrity for
# this version, read and pinned by ` + "`observer cloud-session init`" + `.
NPM_SHA512_X64=` + shellQuote(npmPinHex(opts.NpmPins, "x64")) + `
NPM_SHA512_ARM64=` + shellQuote(npmPinHex(opts.NpmPins, "arm64")) + `
`)
	}
	b.WriteString(`# Accepted vendor verification keys, newest first (internal/update/vendorkey.go).
VENDOR_KEYS=` + shellQuote(keys) + `
# RFC 8032 section 7.1 TEST 2 (the one-byte message 0x72): openssl must
# verify it before it is trusted. TEST 1's empty message cannot be used:
# OpenSSL 3.0 refuses a one-shot verify of zero bytes.
RFC_KEY="PUAXw+hDiVqStwqnTRt+vJyYLM8uxJaMwM1V8Sr0Zgw="
RFC_SIG="kqAJqfDUyrhyDoILX2QlQKKye1QWUD+Ps3YiI+vbadoIWsHkPhWZbkWPNhPQ8R2MOHsurrQwKu6wDSkWErsMAA=="

say() { printf 'cloud-session setup: %s\n' "$*" >&2; }
fail() { say "REFUSED: $*"; exit 1; }
skip() { say "WARNING: $*; observer not installed, the cloud-session hooks stay inactive"; exit 0; }
` + postInstallFunc(opts) + `
# A release binary reports its tag without the leading v.
if [ -x "$PREFIX/observer" ] && [ "$("$PREFIX/observer" --version 2>/dev/null | head -n 1)" = "observer version ${VERSION#v}" ]; then
  say "observer $VERSION already installed at $PREFIX"
  ` + postInstallCall(opts) + `exit 0
fi

[ "$(uname -s)" = Linux ] || skip "not a Linux sandbox"
case "$(uname -m)" in
  x86_64|amd64) arch=x64 ;;
  aarch64|arm64) arch=arm64 ;;
  *) skip "unsupported architecture $(uname -m)" ;;
esac

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

fetch() {
  if command -v curl >/dev/null 2>&1; then
    curl --proto '=https' --tlsv1.2 -fsSL --retry 2 -o "$2" "$1"
  elif command -v wget >/dev/null 2>&1; then
    wget -q --https-only -O "$2" "$1"
  else
    return 1
  fi
}

verify() { # verify <key base64> <sig file> <message file>
  printf '%s\n' '-----BEGIN PUBLIC KEY-----' "MCowBQYDK2VwAyEA$1" '-----END PUBLIC KEY-----' >"$work/vk.pem"
  openssl pkeyutl -verify -pubin -inkey "$work/vk.pem" -rawin -in "$3" -sigfile "$2" >/dev/null 2>&1
}
need_verifier() {
  command -v openssl >/dev/null 2>&1 || fail "openssl (3.x, for Ed25519) is missing; refusing to install an unverified binary"
  printf 'r' >"$work/rfc.msg"
  printf '%s' "$RFC_SIG" | openssl base64 -d -A >"$work/rfc.sig"
  verify "$RFC_KEY" "$work/rfc.sig" "$work/rfc.msg" || fail "this openssl cannot verify Ed25519"
}
vendor_verify() { # vendor_verify <sig file> <message file>
  for k in $VENDOR_KEYS; do
    if verify "$k" "$1" "$2"; then return 0; fi
  done
  return 1
}
install_binary() { # install_binary <extracted observer> <what was verified>
  [ -f "$1" ] && [ ! -L "$1" ] || fail "observer in the download is not a regular file"
  chmod 0755 "$1"
  "$1" --version >/dev/null 2>&1 || fail "the downloaded observer does not run here"
  mkdir -p "$PREFIX"
  mv -f "$1" "$PREFIX/observer.new"
  mv -f "$PREFIX/observer.new" "$PREFIX/observer"
  say "installed observer $VERSION at $PREFIX ($2 verified)"
}

`)
	switch src {
	case InstallRelease:
		b.WriteString(`asset="observer-$VERSION-linux-$arch.tar.gz"
command -v sha256sum >/dev/null 2>&1 || fail "sha256sum is missing"
need_verifier
url="$BASE_URL/download/$VERSION"
fetch "$url/SHA256SUMS" "$work/SHA256SUMS" || skip "cannot reach $BASE_URL"
fetch "$url/$asset" "$work/$asset" || skip "cannot download $asset"
fetch "$url/$asset.sig" "$work/$asset.sig" || fail "release $VERSION publishes no signature for $asset"

want=$(awk -v n="$asset" '{ f = $2; sub(/^\*/, "", f); if (f == n) print $1 }' "$work/SHA256SUMS" | head -n 1)
[ -n "$want" ] || fail "$asset is not in the release SHA256SUMS"
got=$(sha256sum "$work/$asset" | awk '{ print $1 }')
[ "$got" = "$want" ] || fail "checksum mismatch for $asset"
vendor_verify "$work/$asset.sig" "$work/$asset" || fail "the vendor signature on $asset does not verify"

mkdir -p "$work/x"
tar -xzf "$work/$asset" -C "$work/x" observer || fail "$asset has no observer member"
install_binary "$work/x/observer" "sha256 and vendor signature"
`)
	default:
		b.WriteString(`case "$arch" in
  x64) want=$NPM_SHA512_X64 ;;
  arm64) want=$NPM_SHA512_ARM64 ;;
esac
[ -n "$want" ] || skip "no npm integrity pin for linux-$arch in this script (re-run init where the registry is reachable)"
command -v sha512sum >/dev/null 2>&1 || fail "sha512sum is missing"
pkg="observer-linux-$arch"
tgz="$REGISTRY/@superbased/$pkg/-/$pkg-${VERSION#v}.tgz"
fetch "$tgz" "$work/pkg.tgz" || skip "cannot download $pkg ${VERSION#v} from $REGISTRY"
got=$(sha512sum "$work/pkg.tgz" | awk '{ print $1 }')
[ "$got" = "$want" ] || fail "sha512 mismatch for $pkg ${VERSION#v}: not the npm dist.integrity init pinned"

mkdir -p "$work/x"
tar -xzf "$work/pkg.tgz" -C "$work/x" package/bin/observer || fail "$pkg has no bin/observer"
what="npm dist.integrity (sha512)"
# A vendor signature shipped inside the package is checked when present
# (docs/plans/cloud-agents/npm-vendor-signature-proposal-2026-10-31.md).
if tar -tzf "$work/pkg.tgz" | grep -qx 'package/bin/observer.sig'; then
  need_verifier
  tar -xzf "$work/pkg.tgz" -C "$work/x" package/bin/observer.sig || fail "cannot extract the vendor signature"
  vendor_verify "$work/x/package/bin/observer.sig" "$work/x/package/bin/observer" || fail "the vendor signature on bin/observer does not verify"
  what="$what and vendor signature"
fi
install_binary "$work/x/package/bin/observer" "$what"
`)
	}
	if opts.MCP {
		b.WriteString("post_install\n")
	}
	return withOwnership("#!/bin/sh\n", b.String())
}

// setupArgs returns the `observer cloud-session setup` arguments the setup
// script runs after installing (lane CA-C2): only for --mcp. The arguments
// name no agent, so a setup script shared by two agents stays valid.
func setupArgs(opts PlanOptions) []string {
	if !opts.MCP {
		return nil
	}
	args := []string{"cloud-session", "setup", "--mcp"}
	if opts.CodeIntel {
		args = append(args, "--codeintel")
	}
	return args
}

// postInstallFunc renders the post_install shell function ("" without
// --mcp, so the script is byte-identical to one written before lane CA-C2).
// It builds the database (and, with --codeintel, the index) as the user the
// agent runs as: under sudo (the Copilot setup step) that is SUDO_USER, so
// the snapshot holds the files where the agent's hooks and MCP server look.
// A failure only warns: the agent then builds the database on first use.
func postInstallFunc(opts PlanOptions) string {
	args := setupArgs(opts)
	if len(args) == 0 {
		return ""
	}
	quoted := make([]string, len(args))
	for i, a := range args {
		quoted[i] = shellQuote(a)
	}
	return `post_install() { # build what the committed MCP server reads into the snapshot
  set -- "$PREFIX/observer" ` + strings.Join(quoted, " ") + `
  if [ "$(id -u)" = 0 ] && [ -n "${SUDO_USER:-}" ] && [ "$SUDO_USER" != root ] && command -v sudo >/dev/null 2>&1; then
    set -- sudo -u "$SUDO_USER" -H "$@"
  fi
  "$@" || say "WARNING: cloud-session setup failed; the MCP server builds its database on first use"
}
`
}

// postInstallCall is the call placed before the already-installed exit.
func postInstallCall(opts PlanOptions) string {
	if !opts.MCP {
		return ""
	}
	return "post_install\n  "
}

// renderCopilotSetupSteps renders the dedicated Copilot setup workflow. The
// job must be named copilot-setup-steps (the agent runs that job before it
// starts); it checks the repository out and runs the setup script.
func renderCopilotSetupSteps() string {
	body := `name: Copilot setup steps
on:
  workflow_dispatch:
  push:
    paths:
      - .github/workflows/copilot-setup-steps.yml
jobs:
  copilot-setup-steps:
    runs-on: ubuntu-latest
    permissions:
      contents: read
    steps:
      - uses: actions/checkout@v4
      - name: Install SuperBased Observer (cloud-session)
        run: sudo sh ` + SetupScriptPath + `
`
	return withOwnership("", body)
}

